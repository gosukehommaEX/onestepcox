"""Compute the expected values of the onestepcox tests with ref.py.

Reads the CSV files in data/ (written by export_data.py) and writes the R
helper file tests/testthat/helper-expected.R of the package, plus a plain-text
copy of the values (expected_values.txt) in this folder.

Usage (from any folder): python3 make_expected.py <package root>
"""
import csv
import os
import sys

import numpy as np

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import ref  # noqa: E402

pkg_root = sys.argv[1]


def read_csv(name):
    with open(os.path.join(here, "data", name + ".csv")) as f:
        rows = list(csv.reader(f))
    head, body = rows[0], rows[1:]
    cols = {}
    for j, h in enumerate(head):
        vals = [r[j] for r in body]
        try:
            cols[h] = np.array([float(v) for v in vals])
        except ValueError:
            cols[h] = np.array(vals, dtype=object)
    return cols


ov, gb, ps = read_csv("ovarian"), read_csv("gbsg"), read_csv("pharmacoSmoking")
DATA = {
    "ovarian": (ov["futime"], ov["fustat"], ov["rx"] != 1, None),
    "gbsg": (gb["rfstime"], gb["status"], gb["hormon"] != 0, None),
    "gbsg_grade": (gb["rfstime"], gb["status"], gb["hormon"] != 0, gb["grade"]),
    "pharmacoSmoking": (ps["ttr"], ps["relapse"], ps["grp"] != "combination", None),
    "pharmacoSmoking_ageGroup2": (ps["ttr"], ps["relapse"], ps["grp"] != "combination", ps["ageGroup2"]),
}
CHECKSUMS = {
    "ovarian": [("futime", ov["futime"]), ("fustat", ov["fustat"]), ("rx", ov["rx"])],
    "gbsg": [("rfstime", gb["rfstime"]), ("status", gb["status"]), ("hormon", gb["hormon"]),
             ("grade", gb["grade"])],
    "pharmacoSmoking": [("ttr", ps["ttr"]), ("relapse", ps["relapse"]),
                        ("grp_patchOnly", (ps["grp"] == "patchOnly").astype(float)),
                        ("ageGroup2_50plus", (ps["ageGroup2"] == "50+").astype(float))],
}
ETA_DERIV = -0.3

est, der, tot = [], [], []
for name, (t, e, g, s) in DATA.items():
    rows = ref.risk_table(t, e, g, s)
    tot.append((name, len(rows), sum(r[2] for r in rows), sum(r[3] for r in rows),
                sum(r[4] for r in rows), sum(r[5] for r in rows)))
    for ties in ["efron", "breslow"]:
        vals = ref.all_methods(t, e, g, s, ties)
        for m in ref.METHODS:
            est.append((name, ties, m, float(vals[m][0]), float(vals[m][1])))
        U, I, J, L = ref.derivs(ETA_DERIV, rows, ties)
        der.append((name, ties, ETA_DERIV, U, I, J, L))


def fmt(x):
    return x if isinstance(x, str) else repr(float(x))


def r_table(obj, cols):
    """R code that builds a data frame from a whitespace-separated table."""
    lines = [f'{obj} <- utils::read.table(header = TRUE, stringsAsFactors = FALSE, text = "',
             " ".join(cols)]
    for r in rows_of[obj]:
        lines.append(" ".join(fmt(x) for x in r))
    lines.append('")')
    return "\n".join(lines)


rows_of = {"expected_estimates": est, "expected_derivs": der, "expected_risk_totals": tot}
out = [
    "# Generated by tools/test_expected/make_expected.py: do not edit by hand.",
    "# Expected values from an independent Python implementation (ref.py): risk",
    "# sets counted by brute force, derivatives written per event time, and the",
    "# Cox estimate found by Brent's method on the score. Data: ovarian and gbsg",
    "# of 'survival' 3.8-12 and pharmacoSmoking of 'asaur' 0.50.",
    "",
    r_table("expected_estimates", ["data", "ties", "method", "coef", "se"]),
    "",
    r_table("expected_derivs", ["data", "ties", "eta", "U", "I", "J", "L"]),
    "",
    r_table("expected_risk_totals", ["data", "rows", "n_T", "n_C", "O_T", "O"]),
    "",
    "# Column sums of the data used above, to detect a change of the datasets",
    "expected_data_sums <- list(",
]
items = []
for name, cs in CHECKSUMS.items():
    inner = ", ".join(f"{k} = {repr(float(np.sum(v)))}" for k, v in cs)
    items.append(f"  {name} = c({inner})")
out.append(",\n".join(items))
out.append(")")
text = "\n".join(out) + "\n"
dest = os.path.join(pkg_root, "tests", "testthat", "helper-expected.R")
with open(dest, "w", newline="\n") as f:
    f.write(text)

with open(os.path.join(here, "expected_values.txt"), "w", newline="\n") as f:
    f.write("data\tties\tmethod\tcoef\tse\n")
    for r in est:
        f.write("\t".join([r[0], r[1], r[2], repr(r[3]), repr(r[4])]) + "\n")
print("wrote", dest, "with", len(est), "estimates,", len(der), "derivative sets,", len(tot), "risk totals")
